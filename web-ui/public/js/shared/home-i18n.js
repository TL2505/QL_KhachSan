const normalise = value => String(value ?? '').replace(/\s+/g, ' ').trim();
const VI = Object.fromEntries(Object.entries(EN).map(([vi, en]) => [en, vi]));
let language = 'vi';
let observer;
const dynamicLabels = new Map();

export function currentLanguage() { return language; }

export function t(source, values = {}, lang = language) {
  const original = String(source ?? '');
  const key = normalise(original);
  const vi = ALIASES[key] || (Object.hasOwn(EN, key) ? key : VI[key]);
  if (!vi) return original;
  const text = lang === 'en' ? (vi === 'đêm' && Number(values.count) === 1 ? 'night' : (EN[vi] ?? original)) : vi;
  return original.match(/^\s*/)[0] + text.replace(/\{(\w+)\}/g,
    (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match) + original.match(/\s*$/)[0];
}

// Interpolated feedback uses parameters; translated values never become executable HTML.
export function tx(parts, ...values) {
  const source = parts.reduce((text, part, index) => text + part + (index < values.length ? `{${index}}` : ''), '');
  return t(source, values);
}

export function setTranslatedText(element, source, values = {}) {
  if (!element) return;
  dynamicLabels.set(element, { source, values });
  if (element.dataset) delete element.dataset.i18n;
  element.textContent = t(source, values);
}

export function translateUI(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  const selector = '[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria-label], [data-i18n-content]';
  const elements = [...(root.matches?.(selector) ? [root] : []), ...root.querySelectorAll(selector)];
  for (const element of elements) {
    if (element.dataset.i18n) {
      const text = t(element.dataset.i18n, element.dataset.i18nCount ? { count: Number(element.dataset.i18nCount) } : {});
      if (element.textContent !== text) element.textContent = text;
    }
    for (const attribute of ['placeholder', 'title', 'aria-label', 'content']) {
      const source = element.getAttribute(`data-i18n-${attribute}`);
      if (source !== null && element.getAttribute(attribute) !== t(source)) element.setAttribute(attribute, t(source));
    }
  }
}

export function setLanguage(value, root = globalThis.document) {
  language = value === 'en' ? 'en' : 'vi';
  root?.documentElement?.setAttribute('lang', language);
  translateUI(root);
  if (typeof Event === 'function') root?.dispatchEvent?.(new Event('aurelia:languagechange'));
  for (const [element, label] of dynamicLabels) {
    if (element.isConnected === false) { dynamicLabels.delete(element); continue; }
    element.textContent = t(label.source, label.values);
  }
  return language;
}

export function initTranslations(value, root = globalThis.document) {
  setLanguage(value, root);
  if (typeof MutationObserver === 'undefined' || !root?.body) return;
  observer?.disconnect();
  observer = new MutationObserver(records => {
    for (const record of records) {
      for (const node of record.addedNodes) if (node.nodeType === 1) translateUI(node);
    }
  });
  observer.observe(root.body, { childList: true, subtree: true });
}
