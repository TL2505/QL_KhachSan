-- Provider-issued e-invoices are separate from the hotel's internal payment statement.
-- Keep provider identifiers and sync events so invoices can be retrieved and reconciled.
CREATE TABLE IF NOT EXISTS electronic_invoices (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  internal_invoice_id INT NOT NULL,
  booking_id INT NOT NULL,
  parent_einvoice_id BIGINT NULL,
  document_type ENUM('original','adjustment','replacement') NOT NULL DEFAULT 'original',
  provider VARCHAR(40) NOT NULL DEFAULT 'MISA_MEINVOICE',
  provider_environment ENUM('test','production') NOT NULL DEFAULT 'test',
  provider_mode ENUM('POS','HSM_CODE','HSM_NO_CODE') NOT NULL DEFAULT 'HSM_CODE',
  status ENUM('ready','submitting','issued','rejected','sync_required','cancel_pending','cancelled') NOT NULL DEFAULT 'ready',
  provider_ref_id CHAR(36) NOT NULL,
  provider_transaction_id VARCHAR(100) NULL,
  invoice_template_no VARCHAR(40) NULL,
  invoice_series VARCHAR(40) NULL,
  invoice_number VARCHAR(80) NULL,
  tax_authority_code VARCHAR(160) NULL,
  send_tax_status VARCHAR(40) NULL,
  invoice_date DATETIME NULL,
  amount_without_vat DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  vat_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  total_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
  provider_view_url TEXT NULL,
  sync_error_code VARCHAR(120) NULL,
  sync_error_message VARCHAR(700) NULL,
  last_attempt_at DATETIME NULL,
  last_synced_at DATETIME NULL,
  created_by INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_einvoice_provider_ref (provider_ref_id),
  INDEX idx_einvoice_internal (internal_invoice_id, id),
  INDEX idx_einvoice_booking (booking_id, status),
  INDEX idx_einvoice_transaction (provider_transaction_id),
  CONSTRAINT fk_einvoice_internal FOREIGN KEY (internal_invoice_id) REFERENCES invoices(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_einvoice_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_einvoice_parent FOREIGN KEY (parent_einvoice_id) REFERENCES electronic_invoices(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_einvoice_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS electronic_invoice_events (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  electronic_invoice_id BIGINT NOT NULL,
  operation VARCHAR(40) NOT NULL,
  result ENUM('started','success','failed','unknown') NOT NULL,
  provider_http_status SMALLINT NULL,
  provider_error_code VARCHAR(120) NULL,
  request_id CHAR(36) NULL,
  summary VARCHAR(700) NULL,
  actor_user_id INT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_einvoice_event_history (electronic_invoice_id, created_at),
  CONSTRAINT fk_einvoice_event_invoice FOREIGN KEY (electronic_invoice_id) REFERENCES electronic_invoices(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_einvoice_event_actor FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
